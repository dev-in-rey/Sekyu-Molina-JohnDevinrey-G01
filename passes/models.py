import secrets
from django.conf import settings
from django.db import models
from django.db.models import F, Q
from django.utils import timezone


class VisitorPass(models.Model):
    class VisitorType(models.TextChoices):
        GUEST = "GUEST", "Personal Guest"
        DELIVERY = "DELIVERY", "Courier / Delivery"
        SERVICE = "SERVICE", "Utility / Service"
        CONTRACTOR = "CONTRACTOR", "Maintenance Contractor"

    class Status(models.TextChoices):
        PENDING = "PENDING", "Pending"
        ACTIVE = "ACTIVE", "Active"
        USED = "USED", "Used"
        EXPIRED = "EXPIRED", "Expired"
        REVOKED = "REVOKED", "Revoked"

    household = models.ForeignKey(
        "households.Household",
        on_delete=models.PROTECT,
        db_column="household_id",
        related_name="visitor_passes",
        help_text="Destination household issuing the visitor pass.",
    )
    visitor_name = models.CharField(
        max_length=100,
        help_text="Full legal or declared name of the expected visitor or courier.",
    )
    visitor_phone = models.CharField(
        max_length=20,
        blank=True,
        null=True,
        help_text="Optional cellular contact number of the visitor.",
    )
    visitor_type = models.CharField(
        max_length=20,
        choices=VisitorType.choices,
        default=VisitorType.GUEST,
        help_text="Category of visitor defining gate clearance expectations.",
    )
    access_pin = models.CharField(
        max_length=4,
        help_text="4-digit numeric one-time security PIN for guardhouse kiosk validation (BR-10).",
    )
    qr_token = models.CharField(
        max_length=255,
        unique=True,
        help_text="Cryptographic signed token string uniquely identifying this pass (BR-11).",
    )
    valid_from = models.DateTimeField(
        help_text="Date and time when the visitor pass becomes valid for gate entry.",
    )
    valid_until = models.DateTimeField(
        help_text="Date and time when the visitor pass expires.",
    )
    is_multi_entry = models.BooleanField(
        default=False,
        help_text="Designates whether the pass permits multiple entries during its validity window.",
    )
    status = models.CharField(
        max_length=15,
        choices=Status.choices,
        default=Status.ACTIVE,
        help_text="Operational lifecycle status of the visitor pass (BR-12).",
    )
    created_at = models.DateTimeField(
        auto_now_add=True,
        help_text="Timestamp recording when the pass was generated by the resident.",
    )

    class Meta:
        db_table = "visitor_passes"
        ordering = ["-created_at"]
        constraints = [
            models.CheckConstraint(
                condition=Q(valid_until__gt=F("valid_from")),
                name="visitor_passes_valid_window_check",
            ),
            models.CheckConstraint(
                condition=Q(access_pin__regex=r"^[0-9]{4}$"),
                name="visitor_passes_access_pin_digits_check",
            ),
            models.CheckConstraint(
                condition=Q(visitor_type__in=["GUEST", "DELIVERY", "SERVICE", "CONTRACTOR"]),
                name="visitor_passes_visitor_type_valid_check",
            ),
            models.CheckConstraint(
                condition=Q(status__in=["PENDING", "ACTIVE", "USED", "EXPIRED", "REVOKED"]),
                name="visitor_passes_status_valid_check",
            ),
        ]

    @classmethod
    def generate_access_pin(cls):
        active_pins = set(
            cls.objects.filter(status__in=[cls.Status.PENDING, cls.Status.ACTIVE]).values_list(
                "access_pin", flat=True
            )
        )
        for _ in range(50):
            candidate = f"{secrets.randbelow(10000):04d}"
            if candidate not in active_pins:
                return candidate
        return f"{secrets.randbelow(10000):04d}"

    @classmethod
    def generate_qr_token(cls):
        return f"SKP-{secrets.token_urlsafe(24)}"

    def refresh_expiration(self, now=None):
        check_time = now or timezone.now()
        if (
            self.status in (self.Status.PENDING, self.Status.ACTIVE)
            and self.valid_until <= check_time
        ):
            self.status = self.Status.EXPIRED
            if self.pk:
                self.save(update_fields=["status"])
        return self.status

    def save(self, *args, **kwargs):
        if self.visitor_name:
            self.visitor_name = " ".join(self.visitor_name.strip().split())
        if not self.access_pin:
            self.access_pin = self.generate_access_pin()
        if not self.qr_token:
            self.qr_token = self.generate_qr_token()
        super().save(*args, **kwargs)

    def __str__(self):
        return f"Pass #{self.pk or 'new'} - {self.visitor_name} (PIN {self.access_pin})"


class GateAccessLog(models.Model):
    class VisitorType(models.TextChoices):
        GUEST = "GUEST", "Personal Guest"
        DELIVERY = "DELIVERY", "Courier / Delivery"
        SERVICE = "SERVICE", "Utility / Service"
        CONTRACTOR = "CONTRACTOR", "Maintenance Contractor"
        WALK_IN = "WALK_IN", "Walk-In Visitor"

    class VerificationStatus(models.TextChoices):
        GRANTED = "GRANTED", "Granted"
        DENIED = "DENIED", "Denied"
        MANUAL_OVERRIDE = "MANUAL_OVERRIDE", "Manual Override"

    class SyncStatus(models.TextChoices):
        PENDING_SYNC = "PENDING_SYNC", "Pending Sync"
        SYNCED = "SYNCED", "Synced"

    guard_user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.PROTECT,
        db_column="guard_user_id",
        related_name="processed_gate_logs",
        help_text="Security guard user who processed the gate transaction (BR-16).",
    )
    visitor_pass = models.ForeignKey(
        VisitorPass,
        on_delete=models.PROTECT,
        db_column="pass_id",
        null=True,
        blank=True,
        related_name="gate_logs",
        help_text="Validated digital visitor pass (protected against deletion per BR-19).",
    )
    household = models.ForeignKey(
        "households.Household",
        on_delete=models.PROTECT,
        db_column="household_id",
        related_name="gate_logs",
        help_text="Destination household unit visited.",
    )
    visitor_name = models.CharField(
        max_length=100,
        help_text="Full name of the visiting individual recorded at gate clearance.",
    )
    visitor_type = models.CharField(
        max_length=20,
        choices=VisitorType.choices,
        default=VisitorType.GUEST,
        help_text="Classification of visitor at point of entry.",
    )
    entry_timestamp = models.DateTimeField(
        default=timezone.now,
        help_text="Timestamp recording when gate validation occurred.",
    )
    exit_timestamp = models.DateTimeField(
        null=True,
        blank=True,
        help_text="Timestamp recording when the visitor departed through the gatehouse (BR-18).",
    )
    verification_status = models.CharField(
        max_length=20,
        choices=VerificationStatus.choices,
        help_text="Outcome of the gate validation process (BR-17).",
    )
    sync_status = models.CharField(
        max_length=15,
        choices=SyncStatus.choices,
        default=SyncStatus.SYNCED,
        help_text="Cloud synchronization state of the gate log.",
    )
    remarks = models.TextField(
        blank=True,
        null=True,
        help_text="Explanatory notes or reason for denial.",
    )

    class Meta:
        db_table = "gate_access_logs"
        ordering = ["-entry_timestamp"]
        constraints = [
            models.CheckConstraint(
                condition=Q(exit_timestamp__isnull=True)
                | Q(exit_timestamp__gte=F("entry_timestamp")),
                name="gate_access_logs_exit_after_entry_check",
            ),
            models.CheckConstraint(
                condition=Q(
                    verification_status__in=["GRANTED", "DENIED", "MANUAL_OVERRIDE"]
                ),
                name="gate_access_logs_verification_status_check",
            ),
            models.CheckConstraint(
                condition=Q(
                    visitor_type__in=["GUEST", "DELIVERY", "SERVICE", "CONTRACTOR", "WALK_IN"]
                ),
                name="gate_access_logs_visitor_type_check",
            ),
            models.CheckConstraint(
                condition=Q(sync_status__in=["PENDING_SYNC", "SYNCED"]),
                name="gate_access_logs_sync_status_check",
            ),
        ]

    def __str__(self):
        return f"Log #{self.pk or 'new'} - {self.visitor_name} ({self.verification_status})"
